-- 저장된 검색의 시퀀스 인용 (CR-051, DEV-362).
--
-- ## 왜 필요한가
--
-- ADR-007 규칙 5는 "시퀀스를 인용하는 모든 저장물(안전 구간 표식, 저장된
-- 검색의 `seq:` 조건, 공유 URL)은 에폭을 함께 저장한다"를 2026-08-19부터
-- 정하고 있었다. 그런데 셋 중 실제로 그렇게 하는 것은 `safe_marker`
-- 하나뿐이었다 — 마이그레이션 002부터 `repository_id`·`base_branch`·
-- `seq_epoch`을 갖고 있다.
--
-- 에폭이 없으면 재채번 뒤 저장된 `seq:1280..1342`가 **같은 번호로 다른
-- 커밋을 가리킨다**. 오류가 나지 않고 결과가 조용히 달라지므로 조사 도구에서
-- 가장 나쁜 실패다 (FR-SEQ-005 AC-4, FR-SRCH-010 AC-8).
--
-- ## 저장소·브랜치를 열로 두지 않는다
--
-- `safe_marker`는 공간을 열로 갖지만 저장된 검색은 그러지 않는다. 이 자원의
-- 정체성은 질의 문자열이고, `seq:` 조건이 어느 공간을 뜻하는지는 그 문자열의
-- `repo:`·`base:`가 이미 말한다 (FR-SRCH-005 AC-7). 열로 복사하면 사용자가
-- 질의를 고쳤을 때 사본이 낡고 **어느 쪽이 정본인지 아무도 모르게 된다.**
-- `safe_marker`가 열을 갖는 것은 그 자원에 질의가 없기 때문이다.
--
-- ## 만들지 않는 것
--
-- 여러 공간의 에폭 지도, 에폭 집합 지문, 전역 시퀀스 리비전, 서버 측 시퀀스
-- 맥락 스냅숏 표, 저장자의 접근 범위 사본, 에폭 이력 표를 만들지 않는다.
-- `seq:`가 하나의 공간만 지목하므로 **정수 하나면 충분하다.**
--
-- ## 기존 행을 소급해 채우지 않는다
--
-- `query LIKE '%seq:%'`인 행을 찾아 현재 에폭을 넣는 길이 있지만 택하지
-- 않는다. **저장 당시의 에폭은 어디에도 남아 있지 않으므로 현재 값을 넣는
-- 것은 복구가 아니라 추측이고**, 그 추측을 스키마 변경으로 못 박으면 조용한
-- 오답을 영구히 승인하게 된다. 그런 행은 NULL로 남아 `unbound` 상태가 되며
-- 저장자가 명시적으로 다시 연결할 때에만 값이 생긴다.

-- 질의에 `seq:` 범위가 없으면 NULL이고, CR-051 이전에 저장된 행도 NULL이다.
ALTER TABLE saved_search ADD COLUMN seq_epoch INT;

-- 에폭은 1부터다 (`sequence_space.seq_epoch DEFAULT 1`).
--
-- **"질의에 `seq:`가 있으면 값이 있어야 한다"는 CHECK로 강제할 수 없다** —
-- 그 판정은 질의 파서를 실행해야 하고 SQL은 그것을 모른다. 그 불변식은
-- 애플리케이션 계약이며 시험이 지킨다 (데이터 모델 3.4의 상태 표 A~D).
-- 100건 상한을 CHECK로 강제하지 않은 것과 같은 이유의 다른 얼굴이다.
ALTER TABLE saved_search
  ADD CONSTRAINT saved_search_seq_epoch_chk CHECK (seq_epoch IS NULL OR seq_epoch >= 1);
